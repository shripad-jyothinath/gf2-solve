    from dram_geometry import DRAMGeometrySimulator
    from clustering import cluster_addresses_by_bank, extract_candidate_nullspace_vectors

    print("Running Recovery Engine Test on Simulated DRAM Geometry...")
    sim = DRAMGeometrySimulator(num_addr_bits=24, num_bank_bits=4, noise_level=0.05)
    print("\n[Ground Truth Equations]")
    print(sim.describe())

    # Sample addresses
    rng = np.random.RandomState(42)
    addresses = [int(rng.randint(0, 1 << 24) & ~0x3F) for _ in range(96)]

    # Step 1: Cluster
    labels, _, _ = cluster_addresses_by_bank(addresses, sim, num_clusters=16)
    diff_vecs = extract_candidate_nullspace_vectors(addresses, labels, num_addr_bits=24)
    print(f"\nExtracted {len(diff_vecs)} candidate difference vectors.")

    # Step 2: Recover
    engine = AddressMappingRecoveryEngine(num_addr_bits=24, num_bank_bits=4)
    rec_M, diag = engine.recover_mapping(diff_vecs)

    print("\n[Recovered Equations (RREF over GF(2))]")
    for eq in engine.format_equations(rec_M):
        print(eq)

    print(f"\nDiagnostics: {diag}")
    is_match = are_subspaces_equal_gf2(sim.M_true, rec_M)
    print(f"\nExact Subspace Recovery Match: {is_match}")
    assert is_match, "Recovery failed to match true subspace!"
    print("[✓] Recovery Engine Test Succeeded Perfectly!")
