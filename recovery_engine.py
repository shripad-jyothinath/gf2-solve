"""
recovery_engine.py
==================
Robust GF(2) Linear Mapping Recovery Engine.

Integrates:
1. Candidate Null-Space Extraction from Spectral Bank Clusters
2. Consensus Parity Filtering: Testing candidate linear functionals m in (F_2)^n
   against all cluster pairs: Score(m) = Fraction of pairs where m . v = 0 (mod 2).
   - True mapping functionals satisfy m . v = 0 for ~100% of true bank collisions.
   - Spurious/noise functionals satisfy m . v = 0 only ~50% of the time.
3. Basis Assembly via Gaussian Elimination over GF(2):
   Greedily select the k linearly independent functionals with the highest consensus scores.
4. Canonicalization to RREF over GF(2).
"""

import numpy as np
from typing import Tuple, List, Dict, Optional
from gf2_math import (
    rref_gf2,
    rank_gf2,
    orthogonal_complement_gf2,
    are_subspaces_equal_gf2,
    matmul_gf2,
    dot_gf2
)

class AddressMappingRecoveryEngine:
    def __init__(
        self,
        num_addr_bits: int,
        num_bank_bits: int,
        cache_line_bits: int = 6
    ):
        self.n = num_addr_bits
        self.k = num_bank_bits
        self.cache_line_bits = cache_line_bits

    def score_parity_functional(
        self,
        functional: np.ndarray,
        candidate_vectors: np.ndarray
    ) -> float:
        """
        Evaluate the consensus score of a candidate equation m in (F_2)^n:
            Score(m) = (1 / |V|) * sum_v [ (m . v mod 2) == 0 ]
        """
        if len(candidate_vectors) == 0:
            return 0.0
        # Dot products modulo 2 for all vectors simultaneously
        dots = np.bitwise_and(candidate_vectors, functional).sum(axis=1) % 2
        agreement = np.mean(dots == 0)
        return float(agreement)

    def recover_mapping(
        self,
        candidate_diff_vectors: np.ndarray,
        max_search_candidates: int = 1500
    ) -> Tuple[np.ndarray, Dict]:
        """
        Recover the k x n mapping matrix M from candidate null-space vectors.

        Returns:
            recovered_M: k x n matrix in canonical RREF over GF(2).
            diagnostics: Dictionary containing scores, rank, and convergence stats.
        """
        # Step 1: Compute candidate basis vectors from clean subsets
        # We sample subsets of candidate vectors and compute their orthogonal complement
        tested_functionals = []
        seen_hashes = set()

        # Always include candidates generated by computing orthogonal complement of full candidate set
        try:
            direct_null = orthogonal_complement_gf2(candidate_diff_vectors)
            for row in direct_null:
                # Mask out cache line bits (they cannot be part of bank selection in hardware)
                if np.any(row[:self.cache_line_bits] != 0):
                    continue
                if np.all(row == 0):
                    continue
                h = tuple(row)
                if h not in seen_hashes:
                    seen_hashes.add(h)
                    score = self.score_parity_functional(row, candidate_diff_vectors)
                    tested_functionals.append((score, row))
        except Exception:
            pass

        # Bootstrap: Draw random subsets of candidate vectors to generate robust orthogonal complement candidates
        rng = np.random.RandomState(42)
        num_vecs = len(candidate_diff_vectors)
        subset_size = min(max(self.n - self.k + 5, 20), num_vecs)

        num_trials = min(max_search_candidates, 300)
        for _ in range(num_trials):
            if num_vecs < subset_size:
                break
            indices = rng.choice(num_vecs, size=subset_size, replace=False)
            subset = candidate_diff_vectors[indices]
            orth = orthogonal_complement_gf2(subset)
            for row in orth:
                # Mask out cache line bits (they cannot be part of bank selection in hardware)
                if np.any(row[:self.cache_line_bits] != 0):
                    continue
                if np.all(row == 0):
                    continue
                h = tuple(row)
                if h not in seen_hashes:
                    seen_hashes.add(h)
                    score = self.score_parity_functional(row, candidate_diff_vectors)
                    tested_functionals.append((score, row))

        # Also generate single-bit and 2-to-3 bit sparse parity candidates (common in hardware controllers)
        for bit1 in range(self.cache_line_bits, self.n):
            for bit2 in range(bit1, self.n):
                cand = np.zeros(self.n, dtype=np.uint8)
                cand[bit1] = 1
                if bit2 != bit1:
                    cand[bit2] = 1
                h = tuple(cand)
                if h not in seen_hashes:
                    seen_hashes.add(h)
                    score = self.score_parity_functional(cand, candidate_diff_vectors)
                    tested_functionals.append((score, cand))

        # Sort functionals by consensus score descending
        tested_functionals.sort(key=lambda x: x[0], reverse=True)

        # Step 2: Greedily assemble a basis of rank k
        selected_rows = []
        selected_scores = []
        current_basis = []

        for score, functional in tested_functionals:
            # Test if adding this functional increases rank over GF(2)
            test_mat = np.array(current_basis + [functional], dtype=np.uint8)
            if rank_gf2(test_mat) == len(current_basis) + 1:
                current_basis.append(functional)
                selected_rows.append(functional)
                selected_scores.append(score)

            if len(current_basis) == self.k:
                break

        if len(current_basis) < self.k:
            # Fallback if rank k not reached: pad with remaining rows to achieve rank
            print(f"[!] Warning: Only found {len(current_basis)} independent functionals. Rank {self.k} required.")
            recovered_M = np.zeros((self.k, self.n), dtype=np.uint8)
            for i, row in enumerate(current_basis):
                recovered_M[i] = row
        else:
            recovered_M = np.array(current_basis, dtype=np.uint8)

        # Convert to canonical RREF over GF(2)
        rref_M, pivots = rref_gf2(recovered_M)
        # Keep only the non-zero rows
        rref_M = rref_M[~np.all(rref_M == 0, axis=1)]

        diagnostics = {
            "recovered_rank": rank_gf2(recovered_M),
            "target_rank": self.k,
            "mean_consensus_score": float(np.mean(selected_scores)) if selected_scores else 0.0,
            "min_consensus_score": float(np.min(selected_scores)) if selected_scores else 0.0,
            "selected_scores": selected_scores,
            "total_candidates_screened": len(tested_functionals)
        }

        return rref_M, diagnostics

    def format_equations(self, M: np.ndarray) -> List[str]:
        """Convert a recovered mapping matrix M into human-readable XOR equations."""
        eqs = []
        for i in range(M.shape[0]):
            active_bits = [f"A[{col}]" for col in range(M.shape[1]) if M[i, col] == 1]
            eqs.append(f"  b_{i} = " + (" ^ ".join(active_bits) if active_bits else "0"))
        return eqs

